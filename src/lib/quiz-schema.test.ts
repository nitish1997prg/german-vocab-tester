
import { describe, expect, it } from "vitest";

import {
  VocabularyQuestionSchema,
  QuizBatchSchema, GeneratedQuizBatchSchema
} from "./quiz-schema";

const validQuestion = {
  id: "q-001",
  level: "A1",
  word: "der Apfel",
  options: ["Apple", "House", "Book", "Water"],
  correctOptionIndex: 0,
};

const validGeneratedQuestion = {
  level: "A1",
  word: "der Apfel",
  options: [
    "Apple",
    "House",
    "Book",
    "Water",
  ],
  correctOptionIndex: 0,
};



describe("VocabularyQuestionSchema", () => {
  it("accepts a valid vocabulary question", () => {
    const result =
      VocabularyQuestionSchema.safeParse(validQuestion);

    expect(result.success).toBe(true);
  });

  it("rejects an invalid CEFR level", () => {
    const invalidQuestion = {
      ...validQuestion,
      level: "C1",
    };

    const result =
      VocabularyQuestionSchema.safeParse(invalidQuestion);

    expect(result.success).toBe(false);
  });

  it("rejects fewer than four options", () => {
    const invalidQuestion = {
      ...validQuestion,
      options: ["Apple", "House", "Book"],
    };

    const result =
      VocabularyQuestionSchema.safeParse(invalidQuestion);

    expect(result.success).toBe(false);
  });

  it("rejects an invalid correct answer index", () => {
    const invalidQuestion = {
      ...validQuestion,
      correctOptionIndex: 5,
    };

    const result =
      VocabularyQuestionSchema.safeParse(invalidQuestion);

    expect(result.success).toBe(false);
  });

  it("rejects an empty German word", () => {
    const invalidQuestion = {
      ...validQuestion,
      word: "   ",
    };

    const result =
      VocabularyQuestionSchema.safeParse(invalidQuestion);

    expect(result.success).toBe(false);
  });
});



describe("QuizBatchSchema", () => {
  it("accepts a valid question batch", () => {
    const batch = {
      questions: [validQuestion],
    };

    const result = QuizBatchSchema.safeParse(batch);

    expect(result.success).toBe(true);
  });

  it("rejects an empty question batch", () => {
    const batch = {
      questions: [],
    };

    const result = QuizBatchSchema.safeParse(batch);

    expect(result.success).toBe(false);
  });

  it("rejects more than ten questions", () => {
    const batch = {
      questions: Array.from({ length: 11 }, (_, index) => ({
        ...validQuestion,
        id: `q-${index}`,
      })),
    };

    const result = QuizBatchSchema.safeParse(batch);

    expect(result.success).toBe(false);
  });

  
  it("accepts a batch of ten questions", () => {
    const batch = {
      questions: Array.from({ length: 10 }, (_, index) => ({
        ...validQuestion,
        id: `q-${index}`,
      })),
    };

    const result = QuizBatchSchema.safeParse(batch);

    expect(result.success).toBe(true);
  });


  it("rejects a batch containing an invalid question", () => {
    const batch = {
      questions: [
        validQuestion,
        {
          ...validQuestion,
          options: ["Apple", "House"],
        },
      ],
    };

    const result = QuizBatchSchema.safeParse(batch);

    expect(result.success).toBe(false);
  });
});

describe("GeneratedQuizBatchSchema", () => {
  it("accepts a question without an AI-generated ID", () => {
    const result = GeneratedQuizBatchSchema.safeParse({
      questions: [validGeneratedQuestion],
    });

    expect(result.success).toBe(true);
  });

  it("ignores numeric IDs generated by Claude", () => {
    const result = GeneratedQuizBatchSchema.safeParse({
      questions: [
        {
          ...validGeneratedQuestion,
          id: 123,
        },
      ],
    });

    expect(result.success).toBe(true);

    if (result.success) {
      expect(result.data.questions[0]).not.toHaveProperty(
        "id"
      );
    }
  });

  it("rejects questions without exactly four options", () => {
    const result = GeneratedQuizBatchSchema.safeParse({
      questions: [
        {
          ...validGeneratedQuestion,
          options: ["Apple", "House", "Book"],
        },
      ],
    });

    expect(result.success).toBe(false);
  });

  it.each([-1, 4, 1.5])(
    "rejects invalid correctOptionIndex %s",
    (index) => {
      const result = GeneratedQuizBatchSchema.safeParse({
        questions: [
          {
            ...validGeneratedQuestion,
            correctOptionIndex: index,
          },
        ],
      });

      expect(result.success).toBe(false);
    }
  );
});